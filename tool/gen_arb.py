def build(idx):
    out = {'@@locale': 'ar' if idx == 0 else 'en'}
    for key, val in S.items():
        out[key] = val[idx]
        if len(val) > 2:
            out['@' + key] = {'placeholders': val[2]}
        elif idx == 0 and re.search(r'\{\w+\}', val[0]):
            raise SystemExit(f'{key} has placeholders but no metadata')
    return out


